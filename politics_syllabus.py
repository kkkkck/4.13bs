def normalize_lookup_text(value: str) -> str:
    normalized = value.strip()
    for old, new in LOOKUP_REPLACEMENTS:
        normalized = normalized.replace(old, new)
    normalized = re.sub(r"\s+", "", normalized)
    return normalized


def _build_lookup_index() -> dict[int, dict[str, CanonicalChapter]]:
    index: dict[int, dict[str, CanonicalChapter]] = {}
    for root_id, chapters in CANONICAL_CHAPTERS.items():
        root_index: dict[str, CanonicalChapter] = {}
        for chapter_item in chapters:
            candidates = (chapter_item.name, *chapter_item.aliases)
            for candidate in candidates:
                root_index[normalize_lookup_text(candidate)] = chapter_item
        index[root_id] = root_index
    return index


LOOKUP_INDEX = _build_lookup_index()


def has_canonical_catalog(root_id: int) -> bool:
    return root_id in CANONICAL_CHAPTERS


def build_canonical_category_catalog(root_id: int) -> list[dict[str, Any]]:
    chapters = CANONICAL_CHAPTERS.get(root_id)
    if not chapters:
        return []
    return [
        {
            "id": chapter_item.id,
            "name": chapter_item.name,
            "description": "Canonical politics syllabus chapter",
            "sort": chapter_item.sort,
            "parent_id": root_id,
            "practice_mode": 2,
            "status": 1,
        }
        for chapter_item in chapters
    ]


def resolve_canonical_chapter(
    root_id: int | None,
    chapter_name: str,
    *,
    section_hint: str | None = None,
) -> CanonicalChapter | None:
    if root_id is None or not chapter_name:
        return None
    if section_hint:
        override = SECTION_HINT_OVERRIDES.get((root_id, section_hint, chapter_name.strip()))
        if override is not None:
            for chapter_item in CANONICAL_CHAPTERS[root_id]:
                if chapter_item.id == override:
                    return chapter_item
    return LOOKUP_INDEX.get(root_id, {}).get(normalize_lookup_text(chapter_name))


def resolve_canonical_chapter_name(
    root_id: int | None,
    chapter_name: str,
    *,
    section_hint: str | None = None,
) -> str | None:
    chapter_item = resolve_canonical_chapter(root_id, chapter_name, section_hint=section_hint)
    return None if chapter_item is None else chapter_item.name


def resolve_canonical_category_id(
    root_id: int | None,
    chapter_name: str,
    *,
    section_hint: str | None = None,
) -> int | None:
    chapter_item = resolve_canonical_chapter(root_id, chapter_name, section_hint=section_hint)
    return None if chapter_item is None else chapter_item.id
